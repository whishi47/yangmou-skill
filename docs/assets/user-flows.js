function escapeHtml(value) {
  return String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function renderFlows() {
  const host = document.getElementById("flow-grid");
  if (!host) return;
  const lang = window.yangmou.getLang();
  host.innerHTML = window.YANGMOU_FLOWS.map(flow => {
    const title = lang === "en" ? flow.titleEn : flow.title;
    const subtitle = lang === "en" ? flow.subtitleEn : flow.subtitle;
    const cases = (lang === "en" ? flow.casesEn : flow.cases).map(c => `<span class="flow-case">${escapeHtml(c)}</span>`).join("");
    const img = lang === "en" && flow.imgEn ? flow.imgEn : flow.img;
    const steps = (lang === "en" ? flow.stepsEn : flow.steps).map(step => `
      <li class="flow-step">
        <span class="flow-step-label">${escapeHtml(step.label)}</span>
        <p>${escapeHtml(step.text)}</p>
      </li>
    `).join("");
    return `
      <article class="flow-card" id="${escapeHtml(flow.id)}">
        <div class="flow-media">
        <img src="${escapeHtml(img)}" alt="${escapeHtml(lang === "en" ? `${flow.titleEn} workflow diagram` : `${flow.title}流程图`)}" loading="lazy" />
        </div>
        <div class="flow-body">
          <p class="flow-kicker">${escapeHtml(window.yangmou.I18N.flow_kicker[lang])}</p>
          <h2>${escapeHtml(title)}</h2>
          <p class="flow-subtitle">${escapeHtml(subtitle)}</p>
          <div class="flow-cases">${cases}</div>
          <ol class="flow-steps">${steps}</ol>
          <div class="flow-output">
            <h3>${escapeHtml(window.yangmou.I18N.flow_output_heading[lang])}</h3>
            <p>${escapeHtml(lang === "en" ? flow.outputEn : flow.output)}</p>
          </div>
        </div>
      </article>
    `;
  }).join("");
}

function setupFlowLang() {
  const nav = document.querySelector(".nav");
  if (nav && !document.querySelector(".lang-toggle")) {
    nav.appendChild(window.yangmou.createLangToggle());
  }
  window.afterLangChange = renderFlows;
}

function initFlows() {
  window.yangmou.setLang(window.yangmou.getLang());
  setupFlowLang();
  renderFlows();
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initFlows);
} else {
  initFlows();
}
