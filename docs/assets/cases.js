let caseCache = null;

async function loadCases() {
  if (caseCache) return caseCache;
  if (window.YANGMOU_CASES) {
    caseCache = window.YANGMOU_CASES;
    return caseCache;
  }
  const res = await fetch("assets/cases.json");
  if (!res.ok) throw new Error("failed to load cases.json");
  const data = await res.json();
  caseCache = data;
  return data;
}

function cleanText(value) {
  return String(value == null ? "" : value).toLowerCase();
}

function flattenFields(fields) {
  const out = [];
  for (const key of Object.keys(fields || {})) {
    out.push(key);
    out.push(fields[key]);
  }
  return out.join(" ");
}

function caseSearchText(caseItem) {
  return [
    caseItem.name,
    caseItem.book,
    caseItem.chapter,
    caseItem.era,
    caseItem.type,
    caseItem.summary,
    caseItem.background,
    caseItem.lock_mechanism,
    caseItem.open_move,
    caseItem.outcome,
    caseItem.transfer_models,
    caseItem.sales_transfer,
    (caseItem.tags || []).join(" "),
    flattenFields(caseItem.fields),
    caseItem.source_text,
  ].join(" ");
}

function matchesSearch(caseItem, query) {
  if (!query) return true;
  const q = cleanText(query.trim());
  if (!q) return true;
  return cleanText(caseSearchText(caseItem)).includes(q);
}

function scoreSearch(caseItem, query) {
  const q = cleanText(query.trim());
  if (!q) return 0;
  const text = cleanText(caseSearchText(caseItem));
  let score = 0;
  const words = q.split(/\s+/).filter(Boolean);
  for (const w of words) {
    if (text.includes(w)) score += 1;
    if (cleanText(caseItem.name).includes(w)) score += 3;
    if ((caseItem.tags || []).some(t => cleanText(t).includes(w))) score += 2;
    if ((caseItem.pillars || []).some(p => cleanText(p).includes(w))) score += 1.5;
  }
  return score;
}

function filterCases(cases, filters) {
  const q = filters.query || "";
  return cases
    .filter(c => matchesSearch(c, q))
    .filter(c => !filters.field || (c.fields && c.fields[filters.field]))
    .filter(c => !filters.pillar || (c.pillars || []).includes(filters.pillar))
    .filter(c => !filters.book || c.book === filters.book)
    .filter(c => !filters.type || c.type === filters.type)
    .map(c => ({ caseItem: c, score: scoreSearch(c, q) }))
    .sort((a, b) => b.score - a.score || cleanText(a.caseItem.name).localeCompare(cleanText(b.caseItem.name), "zh-Hans-CN"))
    .map(x => x.caseItem);
}

function escapeHtml(value) {
  return String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function pillarClass(pillar) {
  if (pillar === "规则") return "pill";
  if (pillar === "人性") return "pill green";
  return "pill accent";
}

function getLang() {
  try {
    return localStorage.getItem("yangmou-lang") || "zh";
  } catch (err) {
    return "zh";
  }
}

function setLang(lang) {
  try {
    localStorage.setItem("yangmou-lang", lang);
  } catch (err) {
    // ignore
  }
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const bundle = I18N[key];
    if (bundle && bundle[lang]) el.textContent = bundle[lang];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    const bundle = I18N[key];
    if (bundle && bundle[lang]) el.placeholder = bundle[lang];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(el => {
    const key = el.getAttribute("data-i18n-alt");
    const bundle = I18N[key];
    if (bundle && bundle[lang]) el.alt = bundle[lang];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
    const key = el.getAttribute("data-i18n-aria-label");
    const bundle = I18N[key];
    if (bundle && bundle[lang]) el.setAttribute("aria-label", bundle[lang]);
  });
  if (window.afterLangChange) window.afterLangChange(lang);
  const titleKey = document.documentElement.getAttribute("data-i18n-title");
  const descriptionKey = document.documentElement.getAttribute("data-i18n-description");
  if (titleKey && I18N[titleKey]?.[lang]) document.title = I18N[titleKey][lang];
  if (descriptionKey && I18N[descriptionKey]?.[lang]) {
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = I18N[descriptionKey][lang];
  }
}

function createLangToggle() {
  const button = document.createElement("button");
  button.type = "button";
  button.className = "lang-toggle";
  button.setAttribute("aria-label", "Switch language");
  button.textContent = getLang() === "zh" ? "EN" : "中文";
  button.addEventListener("click", () => {
    const next = getLang() === "zh" ? "en" : "zh";
    setLang(next);
    button.textContent = next === "zh" ? "EN" : "中文";
  });
  return button;
}

